//! Input-first generated trees with literal relation and truth tables.

use super::*;

const RELATIONS: [[Truth; 6]; 4] = [
    [Truth::F, Truth::T, Truth::T, Truth::T, Truth::F, Truth::F],
    [Truth::T, Truth::F, Truth::F, Truth::T, Truth::F, Truth::T],
    [Truth::F, Truth::T, Truth::F, Truth::F, Truth::T, Truth::T],
    [Truth::U; 6],
];
const AND: [[Truth; 3]; 3] = [
    [Truth::T, Truth::F, Truth::U],
    [Truth::F, Truth::F, Truth::F],
    [Truth::U, Truth::F, Truth::U],
];
const OR: [[Truth; 3]; 3] = [
    [Truth::T, Truth::T, Truth::T],
    [Truth::T, Truth::F, Truth::U],
    [Truth::T, Truth::U, Truth::U],
];
fn truth_index(value: Truth) -> usize {
    match value {
        Truth::T => 0,
        Truth::F => 1,
        Truth::U => 2,
    }
}
fn not(value: Truth) -> Truth {
    [Truth::F, Truth::T, Truth::U][truth_index(value)]
}

struct Tree {
    kind: Kind,
    result: Expression,
    span: [usize; 2],
    children: Vec<Tree>,
}
fn tree(kind: Kind, result: Expression, span: [usize; 2], children: Vec<Tree>) -> Tree {
    Tree {
        kind,
        result,
        span,
        children,
    }
}
fn wrap(kind: Kind, children: Vec<Tree>) -> Tree {
    let span = [
        children.first().unwrap().span[0],
        children.last().unwrap().span[1],
    ];
    tree(kind, Expression::Truth, span, children)
}
fn and(children: Vec<Tree>) -> Tree {
    wrap(Kind::And, children)
}
fn or(children: Vec<Tree>) -> Tree {
    wrap(Kind::Or, children)
}
fn flatten(input: Tree, nodes: &mut Vec<Node>) -> usize {
    let index = nodes.len();
    nodes.push(node(input.kind, input.result, input.span, None, None));
    let mut previous: Option<usize> = None;
    for child in input.children {
        let child_index = flatten(child, nodes);
        if let Some(previous) = previous {
            nodes[previous].next_sibling = Some(child_index);
        } else {
            nodes[index].first_child = Some(child_index);
        }
        previous = Some(child_index);
    }
    index
}

struct Builder {
    source: Vec<u8>,
    columns: Vec<Column>,
    parameters: Vec<Parameter>,
    values: Vec<ValueObservation>,
}
impl Builder {
    fn push(&mut self, text: &str) {
        self.source.extend_from_slice(text.as_bytes());
    }
    fn operand(&mut self, value: &ValueObservation, origin: usize, column: u8) -> Tree {
        let start = self.source.len();
        let result = Expression::Scalar(value.logical_type);
        let kind = match origin {
            0 => {
                match &value.payload {
                    Payload::Null => self.push("NULL"),
                    Payload::Int64(v) => self.push(&v.to_string()),
                    Payload::Bool(v) => self.push(if *v { "TRUE" } else { "FALSE" }),
                    Payload::Utf8(bytes) => {
                        self.push("'");
                        self.push(
                            &std::str::from_utf8(bytes)
                                .expect("known generated bytes")
                                .replace('\'', "''"),
                        );
                        self.push("'");
                    }
                    Payload::Binary(bytes) => {
                        self.push("X'");
                        for byte in bytes {
                            self.push(&format!("{byte:02X}"));
                        }
                        self.push("'");
                    }
                }
                if value.payload == Payload::Null {
                    Kind::Null
                } else {
                    Kind::Literal(value.clone())
                }
            }
            1 => {
                self.push(if column == 0 { "A" } else { "B" });
                self.columns[usize::from(column)].first_use = Some([start, self.source.len()]);
                Kind::Column { ordinal: column }
            }
            _ => {
                self.push("?");
                let ordinal =
                    u16::try_from(self.parameters.len() + 1).expect("at most two markers");
                self.parameters.push(Parameter {
                    ordinal,
                    spec: spec(
                        value.logical_type,
                        if matches!(value.logical_type, TypeTag::Utf8 | TypeTag::Binary) {
                            Some(65536)
                        } else {
                            None
                        },
                        true,
                    ),
                    span: [start, self.source.len()],
                });
                self.values.push(value.clone());
                Kind::Parameter { ordinal }
            }
        };
        let result = if kind == Kind::Null {
            Expression::UntypedNull
        } else {
            result
        };
        tree(kind, result, [start, self.source.len()], vec![])
    }
    fn compare(
        &mut self,
        left: &ValueObservation,
        right: &ValueObservation,
        origins: usize,
        op: usize,
    ) -> Tree {
        let left = self.operand(left, origins / 3, 0);
        self.push([" = ", " <> ", " < ", " <= ", " > ", " >= "][op]);
        let right = self.operand(right, origins % 3, 1);
        let scalar_type = match (left.result, right.result) {
            (Expression::Scalar(tag), _) | (_, Expression::Scalar(tag)) => Some(tag),
            _ => None,
        };
        wrap(
            Kind::Compare {
                op: [
                    Comparison::Eq,
                    Comparison::Ne,
                    Comparison::Lt,
                    Comparison::Le,
                    Comparison::Gt,
                    Comparison::Ge,
                ][op],
                scalar_type,
            },
            vec![left, right],
        )
    }
    fn constant(&mut self, truth: Truth) -> Tree {
        let values = match truth {
            Truth::T => (
                value(TypeTag::Int64, Payload::Int64(0)),
                value(TypeTag::Int64, Payload::Int64(0)),
            ),
            Truth::F => (
                value(TypeTag::Int64, Payload::Int64(0)),
                value(TypeTag::Int64, Payload::Int64(1)),
            ),
            Truth::U => (
                value(TypeTag::Int64, Payload::Null),
                value(TypeTag::Int64, Payload::Null),
            ),
        };
        self.compare(&values.0, &values.1, 0, 0)
    }
}

fn pair(
    tag: TypeTag,
    relation: usize,
    seed: u64,
    operation: usize,
) -> (ValueObservation, ValueObservation) {
    // Choose the desired relation first and spell values that realize it. No
    // production or generic comparator is called to discover the relation.
    let (low, high) = match tag {
        TypeTag::Int64 => {
            let base =
                i64::try_from((seed % 1_000_000) * 2048 + u64::try_from(operation % 2048).unwrap())
                    .unwrap();
            (Payload::Int64(base), Payload::Int64(base + 1))
        }
        TypeTag::Bool => (Payload::Bool(false), Payload::Bool(true)),
        TypeTag::Utf8 => {
            let prefix = format!("v{seed:x}:{operation:x}:");
            (
                Payload::Utf8(format!("{prefix}a").into_bytes()),
                Payload::Utf8(format!("{prefix}b").into_bytes()),
            )
        }
        TypeTag::Binary => {
            let prefix = [
                u8::try_from(seed % 256).unwrap(),
                u8::try_from(operation % 256).unwrap(),
            ];
            (
                Payload::Binary([prefix.as_slice(), &[0x7f]].concat()),
                Payload::Binary([prefix.as_slice(), &[0x80]].concat()),
            )
        }
    };
    let (left, right) = match relation {
        0 => (low, high),
        1 => (low.clone(), low),
        2 => (high, low),
        3 => (Payload::Null, low),
        4 => (low, Payload::Null),
        _ => (Payload::Null, Payload::Null),
    };
    (value(tag, left), value(tag, right))
}

fn generated(seed: u64, operation: usize) -> Case {
    let k = usize::try_from(seed % 1_000_000).unwrap();
    let relation = (k * 17 + operation) % 6;
    let origins = (k * 5 + operation / 6) % 9;
    let op = (k * 3 + operation / 54) % 6;
    let template = (k + operation) % 8;
    let tag = [
        TypeTag::Int64,
        TypeTag::Bool,
        TypeTag::Utf8,
        TypeTag::Binary,
    ][(k + operation / 9) % 4];
    let (left, right) = pair(tag, relation, seed, operation);
    let scalar_spec = spec(
        tag,
        if matches!(tag, TypeTag::Utf8 | TypeTag::Binary) {
            Some(65536)
        } else {
            None
        },
        true,
    );
    let mut builder = Builder {
        source: format!("/*seed={seed};operation={operation}*/ ").into_bytes(),
        columns: vec![
            Column {
                name: b"A".to_vec(),
                quoted: false,
                spec: scalar_spec,
                first_use: None,
            },
            Column {
                name: b"B".to_vec(),
                quoted: false,
                spec: scalar_spec,
                first_use: None,
            },
        ],
        parameters: vec![],
        values: vec![],
    };
    let begin = builder.source.len();
    let base_truth = RELATIONS[relation.min(3)][op];
    let truth;
    let expression = match template {
        0 => {
            truth = base_truth;
            or(vec![and(vec![builder.compare(&left, &right, origins, op)])])
        }
        1 => {
            builder.push("NOT ");
            let child = builder.compare(&left, &right, origins, op);
            truth = not(base_truth);
            or(vec![and(vec![tree(
                Kind::Not,
                Expression::Truth,
                [begin, child.span[1]],
                vec![child],
            )])])
        }
        2 => {
            builder.push("(");
            let child = or(vec![and(vec![builder.compare(&left, &right, origins, op)])]);
            builder.push(")");
            truth = base_truth;
            or(vec![and(vec![tree(
                Kind::Group,
                Expression::Truth,
                [begin, builder.source.len()],
                vec![child],
            )])])
        }
        3 => {
            let child = builder.compare(&left, &right, origins, op);
            builder.push(" AND ");
            let rhs = builder.constant(Truth::T);
            truth = AND[truth_index(base_truth)][0];
            or(vec![and(vec![child, rhs])])
        }
        4 => {
            let child = builder.compare(&left, &right, origins, op);
            builder.push(" OR ");
            let rhs = builder.constant(Truth::F);
            truth = OR[truth_index(base_truth)][1];
            or(vec![and(vec![child]), and(vec![rhs])])
        }
        5 => {
            builder.push("NOT (");
            let group_start = begin + 4;
            let child = builder.compare(&left, &right, origins, op);
            builder.push(" OR ");
            let rhs = builder.constant(Truth::U);
            builder.push(")");
            let group = tree(
                Kind::Group,
                Expression::Truth,
                [group_start, builder.source.len()],
                vec![or(vec![and(vec![child]), and(vec![rhs])])],
            );
            truth = not(OR[truth_index(base_truth)][2]);
            or(vec![and(vec![tree(
                Kind::Not,
                Expression::Truth,
                [begin, builder.source.len()],
                vec![group],
            )])])
        }
        6 => {
            builder.push("(");
            let child = builder.compare(&left, &right, origins, op);
            builder.push(" AND ");
            let rhs = builder.constant(Truth::F);
            builder.push(")");
            let group = tree(
                Kind::Group,
                Expression::Truth,
                [begin, builder.source.len()],
                vec![or(vec![and(vec![child, rhs])])],
            );
            builder.push(" OR ");
            let last = builder.constant(Truth::U);
            truth = OR[truth_index(AND[truth_index(base_truth)][1])][2];
            or(vec![and(vec![group]), and(vec![last])])
        }
        _ => {
            builder.push("NOT NOT ");
            let child = builder.compare(&left, &right, origins, op);
            let inner = tree(
                Kind::Not,
                Expression::Truth,
                [begin + 4, child.span[1]],
                vec![child],
            );
            truth = not(not(base_truth));
            or(vec![and(vec![tree(
                Kind::Not,
                Expression::Truth,
                [begin, inner.span[1]],
                vec![inner],
            )])])
        }
    };
    let root = wrap(Kind::Predicate, vec![expression]);
    let span = root.span;
    let mut nodes = Vec::new();
    flatten(root, &mut nodes);
    builder.push("; --end\n");
    let hints = Some(
        builder
            .parameters
            .iter()
            .map(|p| Some(p.spec.logical_type))
            .collect(),
    );
    Case {
        id: format!("generated/{seed}/{operation}"),
        family: "generated",
        source: builder.source,
        columns: vec![
            ColumnInput {
                raw_name: b"A".to_vec(),
                spec: scalar_spec,
            },
            ColumnInput {
                raw_name: b"B".to_vec(),
                spec: scalar_spec,
            },
        ],
        hints,
        row: vec![left, right],
        parameters: builder.values,
        evaluate: true,
        expected: Observation {
            plan: Some(Plan {
                span,
                nodes,
                columns: builder.columns,
                parameters: builder.parameters,
            }),
            compile_error: None,
            evaluation_attempted: true,
            truth: Some(truth),
            where_keep: Some(truth == Truth::T),
            eval_error: None,
            complete: true,
        },
    }
}

/// Exact seed/operation inputs; each operation is one compile plus one evaluate.
/// Required seeds are0..64 with128 operations; expanded seeds0..256 use1024.
pub fn generated_cases(seed: u64, operations: usize) -> Vec<Case> {
    (0..operations)
        .map(|operation| generated(seed, operation))
        .collect()
}
